def extra_levels_for(career: str, skills: list | None = None) -> list:
    """The 4 finale levels for a career (deep-copied so callers can't mutate data)."""
    import copy
    import re as _re
    key = career if career in _EXTRA_LEVELS else "Software Developer"
    blob = " ".join(skills or []).lower()
    if key in _DEV_CAREERS and _re.search(r"\bjava\b|spring", blob):
        return copy.deepcopy(_JAVA_TRACK)
    return copy.deepcopy(_EXTRA_LEVELS[key])


def roadmap_task_totals(career: str, skills: list | None = None) -> int:
    """Single source of truth for roadmap task totals (phases + finale levels).
    Used by the roadmap levels API, Analytics and the Dashboard so every % matches."""
    template = ROADMAPS.get(career)
    if not template:
        return 0
    return (
        sum(len(p["tasks"]) for p in template["phases"])
        + sum(len(l["tasks"]) for l in extra_levels_for(career, skills))
    )

