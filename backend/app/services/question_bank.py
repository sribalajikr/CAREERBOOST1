def pools_for_career(career: str, skills: Optional[List[str]] = None) -> List[List[Q]]:
    """Domain pools for a career, expanded with pools matching the user's skills."""
    pools = list(CAREER_POOLS.get(career, [SOFTWARE]))
    blob = " ".join(skills or []).lower()
    for pattern, pool in _SKILL_POOL_HINTS:
        if re.search(pattern, blob) and pool not in pools:
            # QA skill on a dev role ranks high; others append
            pools.insert(0, pool) if pool is QA or pool is JAVA else pools.append(pool)
    return pools


def pool_for_career(career: str, skills: Optional[List[str]] = None) -> List[Q]:
    """All questions relevant to a career — core + domain pools (+ skill-matched pools)."""
    pools = pools_for_career(career, skills)
    seen, out = set(), []
    for q in TECHNICAL_UNIVERSAL + [q for pool in pools for q in pool]:
        if q["id"] not in seen:
            seen.add(q["id"])
            out.append(q)
    return out


def domain_ids_for(career: str, skills: Optional[List[str]] = None) -> set:
    """IDs of career/skill-specific (non-core) questions — the engine prefers these."""
    ids: set = set()
    for pool in pools_for_career(career, skills):
        ids.update(q["id"] for q in pool)
    return ids


def primary_ids_for(career: str, skills: Optional[List[str]] = None) -> set:
    """IDs of the career's PRIMARY domain pool — the role's own questions
    (e.g. Java questions for a Java Developer). The engine serves these
    first so a role change actually flows into prep questions."""
    pools = pools_for_career(career, skills)
    return {q["id"] for q in pools[0]} if pools else set()


def all_categories_for(career: str) -> List[str]:
    cats = []
    for q in pool_for_career(career):
        if q["category"] not in cats:
            cats.append(q["category"])
    return cats


